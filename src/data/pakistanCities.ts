// Fast Lookup Map by City Name (case-insensitive)
export const PAKISTAN_CITIES_MAP: Record<string, PakistanCityMeta> =
  PAKISTAN_CITIES_DATA.reduce((acc, item) => {
    acc[item.name.toLowerCase()] = item;
    acc[item.name] = item;
    return acc;
  }, {} as Record<string, PakistanCityMeta>);

// Helper: Find city metadata by name or fallback
export function getPakistanCityMeta(cityName: string): PakistanCityMeta {
  const normalized = cityName.trim().toLowerCase();
  if (PAKISTAN_CITIES_MAP[normalized]) {
    return PAKISTAN_CITIES_MAP[normalized];
  }
  // Try partial match
  const found = PAKISTAN_CITIES_DATA.find((c) =>
    normalized.includes(c.name.toLowerCase()) || c.name.toLowerCase().includes(normalized)
  );
  if (found) return found;

  // Safe fallback (Karachi coordinates & KMC NOC)
  return {
    name: cityName || 'Karachi',
    province: 'Sindh',
    division: 'Karachi',
    tier: 2,
    lat: 24.8607,
    lng: 67.0011,
    defaultAuthorityNoc: 'KMC',
    taxRatePercent: 13,
  };
}

// Group cities by Province for categorized selectors & accordions
export const CITIES_BY_PROVINCE: Record<
  string,
  PakistanCityMeta[]
> = PAKISTAN_CITIES_DATA.reduce((acc, c) => {
  if (!acc[c.province]) {
    acc[c.province] = [];
  }
  acc[c.province].push(c);
  return acc;
}, {} as Record<string, PakistanCityMeta[]>);
